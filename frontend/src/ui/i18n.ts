const DICTS: Record<Lang, Dict> = { ja, zh, en }

export const translate = (lang: Lang, key: string): string =>
  DICTS[lang]?.[key] ?? ja[key] ?? key

// KEY+ARGS 方式のログ翻訳. テンプレートを表示言語 (欠落時 ja, さらに欠落時 key) から引き,
// {placeholder} を args の値で埋める.
export const translateMsg = (
  lang: Lang,
  key: string,
  args?: Record<string, unknown> | null,
): string => {
  const template = DICTS[lang]?.[key] ?? ja[key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(args?.[k] ?? ''))
}

export const detectLang = (): Lang => {
  const n = (navigator.language || 'ja').toLowerCase()
  if (n.startsWith('zh')) return 'zh'
  if (n.startsWith('en')) return 'en'
  return 'ja'
}
